#!/usr/bin/env python3
"""Convert Misaki's Unicode BDF to an 8-row JIS font, or embed that font as C."""
import argparse
from pathlib import Path


def glyph_index(character):
    try:
        encoded = chr(character).encode("cp932")
    except UnicodeEncodeError:
        return None
    if len(encoded) == 1:
        return encoded[0]
    lead, trail = encoded
    row = (lead - (0x81 if lead < 0xA0 else 0xC1)) * 2
    column = trail - (0x40 if trail < 0x7F else 0x41)
    if trail >= 0x9F:
        row += 1
        column = trail - 0x9F
    return 256 + row * 94 + column if 0 <= row < 94 and 0 <= column < 94 else None


def convert_bdf(path):
    font = bytearray(bytes([0xFE, 0x82, 0x82, 0x82, 0x82, 0x82, 0xFE, 0]) * (256 + 94 * 94))
    lines = iter(path.read_text().splitlines())
    for line in lines:
        if line.startswith("ENCODING "):
            index = glyph_index(int(line.split()[1]))
        elif line.startswith("BBX "):
            width, height, x, y = map(int, line.split()[1:])
        elif line == "BITMAP":
            rows = [int(next(lines), 16) for _ in range(height)]
            if index is None:
                continue
            glyph = bytearray(8)
            for row, bits in enumerate(rows):
                target = 7 - height - y + row
                if 0 <= target < 8:
                    glyph[target] = (bits >> x if x >= 0 else bits << -x) & 255
            font[index * 8:index * 8 + 8] = glyph
    return font


def unicode_table():
    # Indexed like the font, avoiding a platform-specific Shift-JIS converter.
    values = []
    for index in range(256 + 94 * 94):
        if index < 256:
            encoded = bytes([index])
        else:
            row, column = divmod(index - 256, 94)
            lead = row // 2 + (0x81 if row < 62 else 0xC1)
            trail = column + (0x9F if row % 2 else 0x40 if column < 63 else 0x41)
            encoded = bytes([lead, trail])
        try:
            values.append(ord(encoded.decode("cp932")))
        except UnicodeDecodeError:
            values.append(0)
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    if args.source.suffix.lower() == ".bdf":
        args.output.write_bytes(convert_bdf(args.source))
    else:
        font = args.source.read_bytes()
        if len(font) != (256 + 94 * 94) * 8:
            parser.error("invalid packed font size")
        rows = [",".join(str(b) for b in font[i:i + 32]) for i in range(0, len(font), 32)]
        unicode = unicode_table()
        mapping = [",".join(str(c) for c in unicode[i:i + 32]) for i in range(0, len(unicode), 32)]
        args.output.write_text("/* Generated by compileTownsFont.py; see third_party/misaki/LICENSE.txt. */\n"
                               "const unsigned char abTownsFont[] = {\n" + ",\n".join(rows) + "\n};\n"
                               "const unsigned short awTownsUnicode[] = {\n" + ",\n".join(mapping) + "\n};\n")


if __name__ == "__main__":
    main()

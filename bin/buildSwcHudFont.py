#!/usr/bin/env python3
"""Generate the SDL-only SWC HUD bitmap from the bundled Anonymous Pro font.

Requires Pillow only when regenerating; normal builds use the checked-in header.
This performs offline font conversion and does not launch the game or SDL.
"""
from hashlib import sha256
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, __version__, features


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "third_party/anonymouspro/AnonymousPro-Regular.ttf"
DESTINATION = ROOT / "src/sdl/swc_hud_font.h"
SOURCE_SHA256 = "46d8b9a5f4b38fc9d30f3cdd676d4c6f78a9bef949bb1a8304216cc731eb87f8"


def main():
    if sha256(SOURCE.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise SystemExit("Anonymous Pro source differs from the recorded font")
    font = ImageFont.truetype(SOURCE, 9, layout_engine=ImageFont.Layout.BASIC)
    rows = []
    for code in range(32, 127):
        character = chr(code)
        left, top, right, bottom = font.getbbox(character, anchor="ls")
        if (font.getlength(character) != 5 or left < -1 or right > 7 or
                top < -9 or bottom > 3):
            raise SystemExit(f"Glyph {code} does not fit the recorded HUD metrics")
        bitmap = Image.new("1", (8, 12))
        ImageDraw.Draw(bitmap).text((1, 9), character, font=font, fill=1, anchor="ls")
        glyph = [sum(int(bool(bitmap.getpixel((x, y)))) << (7 - x)
                     for x in range(8)) for y in range(12)]
        rows.append("    {" + ", ".join(f"0x{row:02x}" for row in glyph) +
                    f"}}, /* U+{code:04X} */")
    header = f"""/* SWC HUD Bitmap: derived from Anonymous Pro Regular, 9 pixels, monochrome.
 * Copyright (c) 2009, Mark Simonson. Licensed under SIL OFL 1.1.
 * See third_party/anonymouspro/OFL.txt and README.md.
 * Generated by bin/buildSwcHudFont.py; do not edit glyphs by hand.
 * Pillow {__version__}, FreeType {features.version_module('freetype2')}.
 * Source SHA-256: {SOURCE_SHA256}
 */
#ifndef SWC_HUD_FONT_H
#define SWC_HUD_FONT_H

#define SWC_HUD_FONT_WIDTH 8
#define SWC_HUD_FONT_HEIGHT 12
#define SWC_HUD_FONT_BEARING 1
#define SWC_HUD_FONT_BASELINE 9
#define SWC_HUD_FONT_ADVANCE 5

static const unsigned char abSwcHudFont[95][SWC_HUD_FONT_HEIGHT] = {{
"""
    DESTINATION.write_text(header + "\n".join(rows) + "\n};\n\n#endif\n")
    print(f"Generated {DESTINATION.relative_to(ROOT)}: 95 ASCII glyphs")


if __name__ == "__main__":
    main()

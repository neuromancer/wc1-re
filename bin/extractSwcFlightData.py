#!/usr/bin/env python3
"""Recover Mac demo flight constants from CODE_08's original instructions.

Requires capstone. Inputs are the original CODE_08 resource and the expanded
DATA/A5 images produced by the existing SWC Ghidra analysis. This evaluates
only the straight-line constant stores in init_data_struct1/2, not game code.
"""
import argparse
import hashlib
import json
import struct
from pathlib import Path

from capstone import Cs, CS_ARCH_M68K, CS_MODE_BIG_ENDIAN, CS_MODE_M68K_020
from capstone.m68k_const import (
    M68K_OP_IMM, M68K_OP_REG, M68K_OP_MEM, M68K_REG_A5,
    M68K_AM_REGI_ADDR, M68K_AM_REGI_ADDR_DISP, M68K_AM_ABSOLUTE_DATA_LONG,
    M68K_AM_ABSOLUTE_DATA_SHORT,
)


def recover(code):
    table = bytearray(83 * 204)
    for index in range(83):
        table[index * 204 + 0xca] = 1  # CODE_08 +0x0286..0x02ac.
    registers = {M68K_REG_A5: 0x10000}
    decoder = Cs(CS_ARCH_M68K, CS_MODE_BIG_ENDIAN | CS_MODE_M68K_020)
    decoder.detail = True

    def address(operand):
        if operand.address_mode == M68K_AM_REGI_ADDR:
            return registers[operand.reg]
        if operand.address_mode == M68K_AM_REGI_ADDR_DISP:
            return registers[operand.mem.base_reg] + operand.mem.disp
        if operand.address_mode in (M68K_AM_ABSOLUTE_DATA_LONG,
                                    M68K_AM_ABSOLUTE_DATA_SHORT):
            return operand.imm
        raise ValueError("Unexpected addressing mode")

    def read(operand):
        if operand.type == M68K_OP_REG:
            return registers[operand.reg]
        if operand.type == M68K_OP_IMM:
            return operand.imm
        if operand.type == M68K_OP_MEM and address(operand) == 0x8c76:
            return 0x20000
        raise ValueError("Unexpected memory read")

    for start, end in ((0x2ae, 0x47b8), (0x47cc, 0x66d2)):
        cursor = start
        for ins in decoder.disasm(code[start:end], start):
            if ins.address != cursor:
                raise ValueError("Undecoded initialization instruction")
            cursor += ins.size
            if ins.mnemonic in ("link.w", "unlk", "rts"):
                continue
            operands = ins.operands
            if ins.mnemonic == "lea.l":
                value = address(operands[0])
            elif ins.mnemonic.startswith("clr."):
                value = 0
            elif ins.mnemonic in ("moveq", "move.l", "move.b", "movea.l"):
                value = read(operands[0])
            else:
                raise ValueError(f"Unexpected instruction at {ins.address:#x}: {ins}")
            destination = operands[-1]
            if destination.type == M68K_OP_REG:
                registers[destination.reg] = value
            else:
                offset = address(destination) - 0x20000
                width = 1 if ins.mnemonic.endswith(".b") else 4
                if offset < 0 or offset + width > len(table):
                    raise ValueError("Store outside object definitions")
                table[offset:offset + width] = (value & ((1 << (8 * width)) - 1)).to_bytes(width, "big")
        if cursor != end:
            raise ValueError(f"Incomplete initialization block: {cursor:#x} != {end:#x}")
    return table


def generate(code, data, negative):
    table = recover(code)
    lines = [
        "/* Generated by bin/extractSwcFlightData.py from the Mac demo.",
        f" * CODE_08 SHA-256: {hashlib.sha256(code).hexdigest()}",
        f" * DATA/0 SHA-256: {hashlib.sha256(data).hexdigest()}",
        f" * Negative A5 SHA-256: {hashlib.sha256(negative).hexdigest()}",
        " * Original entries: init_data_struct1 +0x0286, init_data_struct2 +0x47cc.",
        " * Common WC1/SWC object IDs 0..57; the other Mac IDs remain unsupported.",
        " * DATA/0 animation words are converted from big endian to host integers. */",
    ]
    records = []
    fields = {
        "objectClass": 4, "collisionRadius": 8, "radarRadius": 12,
        "scale": 16, "animationDelay": 20, "damageCapacity": 28,
        "explosionDamage": 32, "maximumVelocity": 36, "cruiseVelocity": 40,
        "acceleration": 48, "pitchRate": 52, "yawRate": 56, "rollRate": 60,
        "afterburnerVelocity": 64, "shieldFore": 170, "shieldAft": 174,
        "armorFront": 178, "armorRear": 182, "armorLeft": 186, "armorRight": 190,
    }
    for index in range(58):
        record = table[index * 204:(index + 1) * 204]
        number = lambda offset: struct.unpack_from(">i", record, offset)[0]
        name_at = number(0)
        name = negative[name_at:negative.index(0, name_at)].decode("mac_roman") if name_at else ""
        animation_at = number(44)
        if animation_at:
            animation = []
            for offset in range(animation_at, len(data), 4):
                command = struct.unpack_from(">I", data, offset)[0]
                animation.append(command)
                if command & 0xf000 in (0x9000, 0xa000):
                    break
                if len(animation) > 256:
                    raise ValueError("Unterminated animation")
            else:
                raise ValueError("Animation reaches the end of DATA/0")
            lines.append(f"static unsigned int swcAnimation{index}[] = {{" +
                         ", ".join(hex(v) for v in animation) + "};")
        values = {field: number(offset) for field, offset in fields.items()}
        for field, value in values.items():
            if field not in ("objectClass", "acceleration") and not -32768 <= value <= 32767:
                raise ValueError(f"Object {index} {field} exceeds shared storage")
        records.append((name, values, number(24), animation_at, record))
    lines.append("\nstatic const ObjectTypeData swcObjectDefinitions[OBJECT_TYPE_COUNT] = {")
    for index, (name, values, lifetime, animation, _) in enumerate(records):
        lines.append(f"    {{ /* {index}: {name} */")
        lines.append(f"        .displayName = {json.dumps(name)},")
        for field, value in values.items():
            lines.append(f"        .{field} = {value},")
        if values["objectClass"] < 12:
            if not -32768 <= lifetime <= 32767:
                raise ValueError("Non-ship lifetime exceeds shared storage")
            lines.append(f"        .lifetime = {lifetime},")
        if animation:
            lines.append(f"        .animation = (unsigned char *)swcAnimation{index},")
        lines.append("    },")
    lines.append("};\n")
    lines.append("static const int swcShipFuel[22] = {" +
                 ", ".join(str(r[2]) for r in records[:22]) + "};")
    lines.append("static const unsigned char swcWeaponCounts[22] = {" +
                 ", ".join(str(r[4][68]) for r in records[:22]) + "};")
    lines.append("static const ShipWeaponSlot swcWeaponLoadouts[22][10] = {")
    for name, _, _, _, record in records[:22]:
        count = record[68]
        if count > 10:
            raise ValueError("Loadout exceeds shared capacity")
        slots = []
        for index in range(count):
            offset = 70 + index * 10
            kind, hardpoint, disabled = struct.unpack_from(">iiB", record, offset)
            if not 0 <= kind < 58 or not 0 <= hardpoint < 63:
                raise ValueError("Unsupported weapon or hardpoint")
            slots.append(f"{{{kind}, {hardpoint}, {disabled}}}")
        lines.append("    {" + ", ".join(slots or ["{0}"]) + f"}}, /* {name} */")
    lines.append("};\n")
    lines.append("/* CODE_04 position_child +0x367a indexes DATA/0 +0x2efe. */")
    lines.append("const ShortVector aSwcChildOffsets[63] = {")
    for index in range(63):
        vector = struct.unpack_from(">3i", data, 0x2efe + index * 12)
        if any(not -32768 <= value <= 32767 for value in vector):
            raise ValueError("Hardpoint exceeds shared coordinate storage")
        lines.append("    {" + ", ".join(str(value) for value in vector) + "},")
    lines.append("};\n")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("code", type=Path)
    parser.add_argument("data", type=Path)
    parser.add_argument("negative_a5", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.code.read_bytes(), args.data.read_bytes(),
                                    args.negative_a5.read_bytes()))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Embed a FONTS.FNT-layout font as C data, after checking its layout.

The layout is that of the game's decompressed fonts: a 16-bit height, the ink
and background colours, 256 widths, then each character's offset split into
256 low and 256 high bytes, and the row-major bitmaps after that.
"""
import argparse
from pathlib import Path

HEADER = 4 + 256 * 3


def check(font, height):
    if not HEADER <= len(font) <= 65535:
        raise ValueError(f"unexpected font size {len(font)}")
    if font[0] | font[1] << 8 != height:
        raise ValueError(f"font height is {font[0] | font[1] << 8}, not {height}")
    for character in range(256):
        width = font[4 + character]
        offset = font[0x104 + character] | font[0x204 + character] << 8
        if width and not HEADER <= offset <= len(font) - width * height:
            raise ValueError(f"character {character:#04x} lies outside the font")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--symbol", required=True)
    parser.add_argument("--size-symbol", required=True)
    parser.add_argument("--height", type=int, required=True)
    args = parser.parse_args()
    font = args.source.read_bytes()
    try:
        check(font, args.height)
    except ValueError as error:
        parser.error(f"{args.source}: {error}")
    rows = [",".join(str(byte) for byte in font[i:i + 32]) for i in range(0, len(font), 32)]
    args.output.write_text(
        f"/* Generated by bin/compileHiResFont.py from {args.source.as_posix()};\n"
        f" * see the LICENSE.txt beside it. */\n"
        f"const unsigned char {args.symbol}[{len(font)}] = {{\n" + ",\n".join(rows) + "\n};\n"
        f"const unsigned int {args.size_symbol} = {len(font)};\n")


if __name__ == "__main__":
    main()

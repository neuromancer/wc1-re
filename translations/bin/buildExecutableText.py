#!/usr/bin/env python3
"""Build the table that lets SDL2 read a player's translated DOS WC.EXE.

Fan translations such as the German v0.4b patch rewrite the English strings of
the DOS WC.EXE B2.4 in place, each within its original length. The port cannot
ship those translations, but with this table it can use them when a player has
patched their own installation.

    python3 translations/bin/buildExecutableText.py --exe data/dos/WC.EXE

No text enters the generated header: each entry is the FNV-1a hash that
FindTranslation computes for an English UI string marked with _(), N_(), C_()
or NC_(), and that string's offset and length in the English executable. The
executable is identified by its size and the CRC32 of its MZ header, which an
in-place translation leaves unchanged. Requires GNU xgettext.
"""
import argparse
from pathlib import Path
import re
import zlib

from updateUiTranslations import extract

FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211
ESCAPES = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\"}


def unquote(text):
    return re.sub(r'\\(.)', lambda match: ESCAPES.get(match.group(1), match.group(1)), text)


def ui_strings(root):
    strings = set()
    for block in extract(root, plain=True).split("\n\n"):
        text = None
        for line in block.splitlines():
            if line.startswith("msgid "):
                text = unquote(line[7:-1])
            elif line.startswith("msgstr"):
                break
            elif text is not None and line.startswith('"'):
                text += unquote(line[1:-1])
        if text:
            strings.add(text)
    return strings


def fnv1a(data):
    value = FNV_OFFSET
    for byte in data:
        value = ((value ^ byte) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--exe", type=Path, required=True, help="the English DOS WC.EXE B2.4")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[2] / "src/port/game/executable_text.h")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    image = args.exe.read_bytes()
    header = (image[8] | image[9] << 8) * 16
    if image[:2] != b"MZ" or not 0 < header < len(image):
        parser.error(f"{args.exe} is not a DOS executable")
    entries = []
    for text in sorted(ui_strings(root)):
        try:
            raw = text.encode("cp437")
        except UnicodeEncodeError:
            continue
        found = image.find(b"\0" + raw + b"\0")
        if found >= 0 and len(raw) < 65536:
            entries.append((fnv1a(raw), found + 1, len(raw)))
    entries.sort()
    lines = [
        "/* Generated by translations/bin/buildExecutableText.py from the English DOS WC.EXE B2.4.",
        " * Each entry is an English UI string's FNV-1a hash, as FindTranslation",
        " * computes it, with the string's offset and length in that executable.",
        " * No text is embedded. */",
        f"#define SDL_EXECUTABLE_TEXT_FILE_SIZE {len(image)}u",
        f"#define SDL_EXECUTABLE_TEXT_HEADER_SIZE 0x{header:x}u",
        f"#define SDL_EXECUTABLE_TEXT_HEADER_CRC 0x{zlib.crc32(image[:header]):08x}u",
        "",
        "static const SdlExecutableText sdlExecutableTexts[] = {",
    ]
    lines += [f"    {{0x{value:016x}ULL, 0x{offset:05x}u, {length}u}}," for value, offset, length in entries]
    lines += ["};", ""]
    args.output.write_text("\n".join(lines), encoding="ascii")
    print(f"Wrote {len(entries)} strings to {args.output}")


if __name__ == "__main__":
    main()
